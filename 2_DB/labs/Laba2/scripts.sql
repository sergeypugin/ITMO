-- 4.	Выдать различные имена преподавателей и число людей с каждой из этих имен, ограничив список именами, встречающимися менее 50 раз на на очной форме обучения.
-- Для реализации использовать соединение таблиц.

SELECT Н_ЛЮДИ.ИМЯ, COUNT(DISTINCT Н_ЛЮДИ.ИД) FROM Н_ЛЮДИ
JOIN Н_СЕССИЯ ON Н_ЛЮДИ.ИД = Н_СЕССИЯ.ЧЛВК_ИД
JOIN Н_ГРУППЫ_ПЛАНОВ ON Н_СЕССИЯ.ГРУППА = Н_ГРУППЫ_ПЛАНОВ.ГРУППА::integer
JOIN Н_ПЛАНЫ ON Н_ГРУППЫ_ПЛАНОВ.ПЛАН_ИД = Н_ПЛАНЫ.ИД
JOIN Н_ФОРМЫ_ОБУЧЕНИЯ ON Н_ПЛАНЫ.ФО_ИД = Н_ФОРМЫ_ОБУЧЕНИЯ.ИД
WHERE Н_ФОРМЫ_ОБУЧЕНИЯ.НАИМЕНОВАНИЕ = 'Очная'
GROUP BY Н_ЛЮДИ.ИМЯ
HAVING COUNT(DISTINCT Н_ЛЮДИ.ИД) < 50;


