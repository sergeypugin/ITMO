-- 1.	Запрос для получения атрибутов из указанных таблиц, применив фильтры по указанным условиям:
-- Таблицы: Н_ЛЮДИ, Н_СЕССИЯ.
-- Вывести атрибуты: Н_ЛЮДИ.ФАМИЛИЯ, Н_СЕССИЯ.ДАТА.
-- Фильтры (AND):
-- a) Н_ЛЮДИ.ИМЯ > Ярослав.
-- b) Н_СЕССИЯ.УЧГОД < 2008/2009.
-- c) Н_СЕССИЯ.УЧГОД < 2001/2002.
-- Вид соединения: INNER JOIN.

SELECT Н_ЛЮДИ.ФАМИЛИЯ, Н_СЕССИЯ.ДАТА FROM Н_ЛЮДИ
INNER JOIN Н_СЕССИЯ ON Н_ЛЮДИ.ИД = Н_СЕССИЯ.ЧЛВК_ИД
WHERE 1=1
  AND Н_ЛЮДИ.ИМЯ > 'Ярослав'
  AND Н_СЕССИЯ.УЧГОД < '2008/2009'
  AND Н_СЕССИЯ.УЧГОД < '2001/2002';

