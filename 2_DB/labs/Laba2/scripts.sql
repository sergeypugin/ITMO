SELECT COUNT(DISTINCT Н_УЧЕНИКИ.ЧЛВК_ИД)
FROM Н_УЧЕНИКИ
JOIN Н_ГРУППЫ_ПЛАНОВ ON Н_УЧЕНИКИ.ГРУППА = Н_ГРУППЫ_ПЛАНОВ.ГРУППА::text
JOIN Н_ПЛАНЫ ON Н_ГРУППЫ_ПЛАНОВ.ПЛАН_ИД = Н_ПЛАНЫ.ИД
JOIN Н_ОТДЕЛЫ ON Н_ПЛАНЫ.ОТД_ИД = Н_ОТДЕЛЫ.ИД
WHERE 1=1
  AND Н_ОТДЕЛЫ.КОРОТКОЕ_ИМЯ = 'КТиУ' -- вместо 'ФКТИУ'
  AND Н_УЧЕНИКИ.ЧЛВК_ИД NOT IN ( -- нет плохих оценок/незачётов/неявок
      SELECT Н_ВЕДОМОСТИ.ЧЛВК_ИД FROM Н_ВЕДОМОСТИ
      WHERE Н_ВЕДОМОСТИ.ОЦЕНКА IN ('2','3','4','незач','неявка')
      )
      AND Н_УЧЕНИКИ.ЧЛВК_ИД IN ( -- есть хотя бы 1 оценка
        SELECT ЧЛВК_ИД FROM Н_ВЕДОМОСТИ
        WHERE ОЦЕНКА IN ('5','99','отлично')
      );

