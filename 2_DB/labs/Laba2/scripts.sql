-- 6.	Получить список студентов, отчисленных после первого сентября 2012 года с очной формы обучения. В результат включить:
-- номер группы;
-- номер, фамилию, имя и отчество студента;
-- номер пункта приказа;
-- Для реализации использовать подзапрос с IN.


SELECT Н_УЧЕНИКИ.ГРУППА AS "Номер группы",
       Н_УЧЕНИКИ.ИД AS "ID",
       Н_ЛЮДИ.ФАМИЛИЯ AS "Фамилия", Н_ЛЮДИ.ИМЯ AS "Имя", Н_ЛЮДИ.ОТЧЕСТВО AS "Отечество",
       Н_УЧЕНИКИ.П_ПРКОК_ИД AS "Номер пункта приказа"
FROM Н_УЧЕНИКИ
JOIN Н_ЛЮДИ ON Н_УЧЕНИКИ.ЧЛВК_ИД = Н_ЛЮДИ.ИД
WHERE 1=1
  AND Н_УЧЕНИКИ.ПРИЗНАК = 'отчисл'
  AND Н_УЧЕНИКИ.КОНЕЦ > '2012-09-01'
  AND Н_УЧЕНИКИ.ГРУППА IN (
      SELECT Н_ГРУППЫ_ПЛАНОВ.ГРУППА FROM Н_ГРУППЫ_ПЛАНОВ
      JOIN Н_ПЛАНЫ ON Н_ГРУППЫ_ПЛАНОВ.ПЛАН_ИД = Н_ПЛАНЫ.ИД::integer
      JOIN Н_ФОРМЫ_ОБУЧЕНИЯ ON Н_ПЛАНЫ.ФО_ИД = Н_ФОРМЫ_ОБУЧЕНИЯ.ИД
      WHERE Н_ФОРМЫ_ОБУЧЕНИЯ.НАИМЕНОВАНИЕ = 'Очная'
  );

