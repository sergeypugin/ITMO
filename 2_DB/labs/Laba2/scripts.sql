-- 7.	Сформировать запрос для получения числа на ФКТИУ отличников.

-- Виды оценок
--ucheb=> select distinct ОЦЕНКА from Н_ВЕДОМОСТИ;
-- ОЦЕНКА
----------
-- 2
-- 3
-- 4
-- 5
-- 99
-- зачет
-- незач
-- неявка
-- осв
